_GENERATOR_FIXTURE_SDL = """
schema { query: Root mutation: Mutation }
interface Node { id: ID! }
type Thing implements Node { id: ID! name: String unused: Int }
type Other implements Node { id: ID! size: Int }
type Stray { id: ID! }
union Result = Thing | Other | Stray
enum Colour { RED GREEN BLUE @deprecated(reason: "gone soon") }
input Nested { a: String b: Int }
input ThingInput { name: String nested: Nested colour: Colour }
type Root {
  node(id: ID!): Node
  search(term: String, legacy: String @deprecated(reason: "use term")): [Result!]!
  unused: String
}
type Mutation { thingUpdate(input: ThingInput!): Thing }
"""


def test_generator_trims_to_what_documents_reach():
    """Offline check of the generator itself. The committed snapshot is only ever
    regenerated by the live runner, so without this a generator regression (a
    placeholder input object, a dropped deprecated argument) would pass offline."""
    full = build_schema(_GENERATOR_FIXTURE_SDL)
    documents = [
        "query A($id: ID!) { node(id: $id) { id ... on Thing { name } } }",
        'query B { search(term: "x") { ... on Other { size } } }',
        "mutation C($input: ThingInput!) { thingUpdate(input: $input) { id } }",
    ]
    sdl = generate_sdl(full, documents)

    assert sdl == generate_sdl(full, list(reversed(documents))), "not order-independent"
    trimmed = build_schema(sdl)
    assert all(validate(trimmed, parse(d)) == [] for d in documents)
    # Input objects in full, recursively, with enums in full (deprecations kept).
    assert set(trimmed.get_type("ThingInput").fields) == {"name", "nested", "colour"}
    assert set(trimmed.get_type("Nested").fields) == {"a", "b"}
    assert trimmed.get_type("Colour").values["BLUE"].deprecation_reason == "gone soon"
    # Full argument signatures, deprecated arguments included.
    assert trimmed.query_type.fields["search"].args["legacy"].deprecation_reason == "use term"
    # Only selected fields; an interface's fields reach every implementer.
    assert set(trimmed.get_type("Thing").fields) == {"id", "name"}
    assert set(trimmed.get_type("Other").fields) == {"id", "size"}
    assert "unused" not in trimmed.query_type.fields
    # Unions keep only reached members.
    assert [t.name for t in trimmed.get_type("Result").types] == ["Other", "Thing"]
    assert trimmed.get_type("Stray") is None


def test_snapshot_carries_deprecated_input_values():
    """Guards against a refresh that forgets ``input_value_deprecation=True``.

    Without deprecated input values the snapshot rejects ``productUpdate(input:)``,
    an argument Shopify still serves. That false drift report is what Story 9.18
    read as a removed argument that was still served."""
    product_update = _SCHEMA.mutation_type.fields["productUpdate"]
    assert product_update.args["input"].deprecation_reason
    webhook_input = _SCHEMA.get_type("WebhookSubscriptionInput")
    assert isinstance(webhook_input, GraphQLInputObjectType)
    assert webhook_input.fields["callbackUrl"].deprecation_reason


