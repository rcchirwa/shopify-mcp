"""Contract test: every GraphQL operation the package sends is checked against a
committed, generated snapshot of the pinned Admin API schema (Story 9.16,
generalizing Stories 9.12, 9.14 and 9.18).

**What this suite proves, and what it does not.** It has two legs:

- ``test_document_matches_pinned_schema`` validates every operation document
  against the snapshot. A failure means the document has DRIFTED: it references
  something the pinned schema does not declare, not even as deprecated. That is
  the class behind every real outage this project has had (``priceRules``,
  ``referringSite``, ``node { ... on Job }``). It is NOT proof the operation is
  broken live. The snapshot can be stale, or the drift can be harmless.
  Confirm by executing the operation before calling a tool broken.
- ``test_emitted_payload_is_accepted_by_pinned_schema`` coerces the variables
  the operations layer actually emits. Document validation cannot see inside an
  input object supplied as a variable (see
  ``test_document_validation_alone_cannot_see_inside_a_variable``). A coercion
  failure means the payload itself is rejected, which is a real break.

Neither leg proves an operation WORKS live. Both check shape against a
recorded schema. Business rules ("Context can't be blank") and semantics
(``productUpdate`` replacing a nested input wholesale; see
``test_nested_input_writes.py``) are out of reach of any schema check.

**The snapshot.** ``admin_schema_snapshot.graphql`` beside this module is
GENERATED by ``tests/support/admin_schema_snapshot.py`` from a live
introspection at the SERVED API version, trimmed to what the discovered
documents reach. Do not hand-edit it. Its input objects carry their real field
sets, and its arguments and input fields include deprecated ones.

**Why deprecated input values matter (Story 9.16).** Story 9.18 read
``productUpdate(input:)`` and ``WebhookSubscriptionInput.callbackUrl`` as
removed on 2026-01, and saw Shopify accept ``input:`` anyway. Both are
DEPRECATED, not removed. The standard introspection query leaves deprecated
arguments and input fields out, so a snapshot built from it rejects operations
Shopify still serves. A query-only probe against the live store on 2026-09-16
showed that Shopify does reject an argument it does not declare
(``Field 'shop' doesn't accept argument 'bogusArg'``).
``test_snapshot_carries_deprecated_input_values`` pins this.

**Refreshing.** See README, "Refreshing the Admin API schema snapshot":
``REFRESH_ADMIN_SCHEMA_SNAPSHOT=1 pytest tests/live/test_admin_schema_snapshot.py``
after bumping ``SHOPIFY_API_VERSION``, or when a document starts selecting
something the snapshot lacks.
"""

