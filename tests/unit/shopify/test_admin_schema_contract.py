def test_a_constant_in_a_file_that_does_not_exist_yet_is_discovered_and_checked(
    tmp_path, monkeypatch
):
    """Proves the sweep is repo-wide by construction, not by a file list.

    Written against a synthetic package: the real tree is (correctly) clean, so
    asserting on it would pass whether or not discovery reaches a new file. The
    package also re-exports the constant from a second module, to prove the
    new document is reported once, under the module that defines it."""
    package = tmp_path / "probe_9_16"
    (package / "deep").mkdir(parents=True)
    (package / "__init__.py").write_text("", encoding="utf-8")
    (package / "deep" / "__init__.py").write_text("", encoding="utf-8")
    (package / "deep" / "new_queries.py").write_text(
        'NEW_QUERY = "query New($id: ID!) { product(id: $id) { notARealField } }"\n'
        'not_upper = "query Hidden { shop { id } }"\n'
        'PROSE = "Not GraphQL at all"\n',
        encoding="utf-8",
    )
    (package / "reexport.py").write_text(
        "from probe_9_16.deep.new_queries import NEW_QUERY\n", encoding="utf-8"
    )
    monkeypatch.syspath_prepend(str(tmp_path))
    try:
        found = discover_documents(tmp_path, "probe_9_16")
    finally:
        for name in [m for m in sys.modules if m.startswith("probe_9_16")]:
            del sys.modules[name]

    assert list(found) == ["probe_9_16.deep.new_queries.NEW_QUERY"]
    errors = validate(_SCHEMA, parse(found["probe_9_16.deep.new_queries.NEW_QUERY"]))
    assert any("notARealField" in str(e) for e in errors), errors


def test_every_query_builder_is_registered():
    """A document assembled at call time is invisible to the constant sweep, so
    every ``_build_*`` function in ``shopify_mcp.shopify.queries`` must have
    outputs in ``builder_documents()``. Scoped to ``shopify.queries`` on purpose:
    ``_build_*`` functions elsewhere build regexes and payloads, not GraphQL."""
    registered = builder_documents()
    builders = []
    for info in pkgutil.iter_modules(queries_package.__path__):
        module = importlib.import_module(f"{queries_package.__name__}.{info.name}")
        for name, function in inspect.getmembers(module, inspect.isfunction):
            if name.startswith("_build_") and function.__module__ == module.__name__:
                builders.append(f"{module.__name__}.{name}")
    assert len(builders) >= 4, f"builder scan found only {builders}; is it still looking?"
    unregistered = [b for b in builders if not any(lbl.startswith(f"{b}[") for lbl in registered)]
    assert unregistered == [], (
        f"{unregistered} build GraphQL at call time but have no entry in "
        "tests/support/admin_schema_snapshot.py:builder_documents()"
    )


