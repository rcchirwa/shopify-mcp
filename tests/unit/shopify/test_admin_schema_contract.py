def test_coercion_rejects_an_unsupplied_required_variable():
    """The old ``"input"`` payload key against the ``$product`` document leaves
    the variable unsupplied."""
    joined = _coercion_errors(UPDATE_PRODUCT, {"input": {"id": _GID, "title": "T"}})
    assert "$product" in joined
    assert "ProductUpdateInput!" in joined


def test_coercion_rejects_a_field_the_input_type_does_not_declare():
    joined = _coercion_errors(
        CREATE_WEBHOOK,
        {
            "topic": "ORDERS_CREATE",
            "webhookSubscription": {"uri": "https://example.com/hook", "bogusField": "x"},
        },
    )
    assert "bogusField" in joined
    assert "WebhookSubscriptionInput" in joined


def test_coercion_rejects_an_undeclared_field_in_a_nested_input_object():
    joined = _coercion_errors(
        UPDATE_PRODUCT, {"product": {"id": _GID, "seo": {"title": "S", "bogusField": "x"}}}
    )
    assert "bogusField" in joined
    assert "SEOInput" in joined


def test_document_validation_alone_cannot_see_inside_a_variable():
    """Pins WHY leg 2 exists, so nobody deletes it as redundant: the same broken
    payload is invisible to ``validate()`` (which takes no variables) and
    rejected by coercion."""
    broken_payload = {
        "topic": "ORDERS_CREATE",
        "webhookSubscription": {"bogusField": "https://example.com/hook", "format": "JSON"},
    }
    assert validate(_SCHEMA, parse(CREATE_WEBHOOK)) == []
    assert not isinstance(_coerce(CREATE_WEBHOOK, broken_payload), dict)
